#!/usr/bin/env node
// Bundles the table engine and the computer player into api/_engine.js for the online-play server.
// `--check` builds in memory and fails if the committed api/_engine.js is out of date.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { rolldown } from "rolldown";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const target = path.join(root, "api", "_engine.js");
const banner = "// GENERATED by scripts/build-room-engine.mjs from src/switch. Do not edit; run `npm run build:engine`.\n";

const bundle = await rolldown({ input: path.join(root, "scripts", "room-engine-entry.ts"), platform: "node", logLevel: "warn" });
const { output } = await bundle.generate({ format: "esm" });
await bundle.close();
const code = banner + output[0].code.replace(/\r\n/g, "\n");

if (process.argv.includes("--check")) {
  let current = "";
  try { current = readFileSync(target, "utf8").replace(/\r\n/g, "\n"); } catch { /* missing */ }
  if (current !== code) { console.error("api/_engine.js is out of date. Run: npm run build:engine"); process.exit(1); }
  console.log("api/_engine.js is up to date.");
} else {
  writeFileSync(target, code);
  console.log(`Wrote api/_engine.js (${code.length} bytes).`);
}
